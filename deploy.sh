#!/usr/bin/env bash
# Deploy the whole eCommerce app to AWS: infrastructure (Terraform), backend
# images (ECR/ECS) and the React frontend (S3/CloudFront). Safe to re-run;
# later runs only roll out what changed.
#
# Usage:
#   ./deploy.sh            # asks before changing infrastructure
#   ./deploy.sh --yes      # no prompt
#
# Optional on first run:
#   NOTIFICATION_EMAIL=you@example.com ./deploy.sh   # get order emails via SNS
#   AWS_REGION=ap-south-1 ./deploy.sh                # default: your AWS CLI region
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")" && pwd)"
INFRA_DIR="$ROOT_DIR/infra"
FRONTEND_DIR="$ROOT_DIR/frontend/react-app"
TFVARS="$INFRA_DIR/terraform.tfvars"
SERVICES="product-service cart-service user-service order-service"

AUTO_APPROVE=""
if [ "${1:-}" = "--yes" ]; then
  AUTO_APPROVE="-auto-approve"
fi

log() { printf '\n==> %s\n' "$*"; }
die() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }
tf() { terraform -chdir="$INFRA_DIR" "$@"; }
tf_var() { echo "var.$1" | tf console | tr -d '"'; }
tf_out() { tf output -raw "$1"; }

# --- 1. Preflight -------------------------------------------------------------
log "Checking prerequisites"
for tool in terraform aws docker node npm curl; do
  command -v "$tool" >/dev/null 2>&1 || die "'$tool' is not installed."
done
docker info >/dev/null 2>&1 || die "Docker is not running. Start Docker Desktop and re-run."
ACCOUNT_ID="$(aws sts get-caller-identity --query Account --output text 2>/dev/null)" \
  || die "AWS CLI has no valid credentials. Run 'aws configure' (or 'aws login') first."

# --- 2. Settings (written once, reused by later runs and destroy.sh) ----------
if [ ! -f "$TFVARS" ]; then
  REGION="${AWS_REGION:-$(aws configure get region || true)}"
  REGION="${REGION:-us-east-1}"
  case "$(uname -m)" in
    arm64 | aarch64) ARCH="ARM64" ;;
    *) ARCH="X86_64" ;;
  esac
  cat >"$TFVARS" <<EOF
aws_region         = "$REGION"
cpu_architecture   = "$ARCH"
notification_email = "${NOTIFICATION_EMAIL:-}"
EOF
  log "Created infra/terraform.tfvars (region=$REGION, arch=$ARCH)"
fi

log "Initializing Terraform"
tf init -input=false

REGION="$(tf_var aws_region)"
ARCH="$(tf_var cpu_architecture)"
export AWS_REGION="$REGION" AWS_DEFAULT_REGION="$REGION"
REGISTRY="$ACCOUNT_ID.dkr.ecr.$REGION.amazonaws.com"
if [ "$ARCH" = "ARM64" ]; then PLATFORM="linux/arm64"; else PLATFORM="linux/amd64"; fi

echo "Account: $ACCOUNT_ID   Region: $REGION   Platform: $PLATFORM"

# --- 3. Container images --------------------------------------------------------
# ECR repos must exist before images can be pushed, and images must exist
# before ECS services start, so create the repos on their own first.
log "Creating ECR repositories"
tf apply -input=false -auto-approve -target=aws_ecr_repository.service

log "Building and pushing service images"
IMAGE_TAG="$(date +%Y%m%d-%H%M%S)"
aws ecr get-login-password | docker login --username AWS --password-stdin "$REGISTRY"
for svc in $SERVICES; do
  repo="$REGISTRY/ecommerce/$svc"
  echo "--- $svc"
  docker build --platform "$PLATFORM" -t "$repo:$IMAGE_TAG" -t "$repo:latest" "$ROOT_DIR/services/$svc"
  docker push "$repo:$IMAGE_TAG"
  docker push "$repo:latest"
done

# --- 4. Infrastructure ------------------------------------------------------------
log "Deploying infrastructure (first run takes ~15-20 min: RDS, NAT Gateway, CloudFront)"
# shellcheck disable=SC2086 # AUTO_APPROVE is intentionally empty or a single flag
tf apply -input=false $AUTO_APPROVE -var "image_tag=$IMAGE_TAG"

API_URL="$(tf_out api_url)"
WEBSITE_URL="$(tf_out website_url)"
BUCKET="$(tf_out frontend_bucket)"
DISTRIBUTION_ID="$(tf_out cloudfront_distribution_id)"
CLUSTER="$(tf_out ecs_cluster)"

# --- 5. Frontend --------------------------------------------------------------------
log "Building frontend"
cat >"$FRONTEND_DIR/src/aws-config.js" <<EOF
// Generated by deploy.sh from Terraform outputs. Re-run ./deploy.sh to refresh.
const awsConfig = {
  Auth: {
    Cognito: {
      userPoolId: '$(tf_out cognito_user_pool_id)',
      userPoolClientId: '$(tf_out cognito_client_id)',
      loginWith: {
        email: true,
      },
    }
  },
  API: {
    baseUrl: '$API_URL'
  }
};

export default awsConfig;
EOF
# DISABLE_ESLINT_PLUGIN: CRA's bundled lint config fails with
# 'Environment key "jest/globals" is unknown'; linting isn't needed to build.
(cd "$FRONTEND_DIR" && npm install --no-audit --no-fund && DISABLE_ESLINT_PLUGIN=true npm run build)

log "Uploading frontend to s3://$BUCKET"
aws s3 sync "$FRONTEND_DIR/build/" "s3://$BUCKET" --delete --exclude "images/*"
aws cloudfront create-invalidation --distribution-id "$DISTRIBUTION_ID" --paths "/*" >/dev/null

# --- 6. Verify ----------------------------------------------------------------------
log "Waiting for backend services to become healthy (up to 10 min)"
ECS_SERVICES=""
for svc in $SERVICES; do ECS_SERVICES="$ECS_SERVICES ecommerce-$svc"; done
# shellcheck disable=SC2086
if aws ecs wait services-stable --cluster "$CLUSTER" --services $ECS_SERVICES; then
  echo "All 4 services are running."
else
  echo "WARNING: services did not stabilize. Check logs:"
  echo "  aws logs tail /ecs/<service-name> --since 15m"
fi

if curl -fsS "$API_URL/products" >/dev/null; then
  echo "API check passed: GET $API_URL/products"
else
  echo "WARNING: GET $API_URL/products failed. Services may still be starting; retry in a minute."
fi

cat <<EOF

============================================================
 Deployed.

 Website: $WEBSITE_URL
 API:     $API_URL

 - Sign up on the website, confirm the code emailed by Cognito, then shop.
 - If you set NOTIFICATION_EMAIL, click the SNS confirmation link in that
   inbox to receive order emails.
 - This setup costs about \$3/day (NAT Gateway, ALB, RDS, Fargate).
   Remove everything when done:  ./destroy.sh
============================================================
EOF
